/**
 * AdShield Pro — community traffic engine (on-device half).
 *
 * The honesty rule of this module: **there is no live traffic unless real observers produced it.**
 *
 *  - A speed sample only exists when this device (or another opted-in device) actually drove the
 *    segment. Nothing is interpolated from history, and no commercial traffic feed is used.
 *  - A segment with no recent observations reports [CongestionLevel.UNKNOWN] ("grey"), never
 *    "green" — "green" means "measured free-flow", not "we have no idea".
 *  - Every level carries the number of contributing samples, their age and a confidence score so
 *    the UI can show *why* it believes something.
 *
 * The class is platform-free; the network uplink lives in `TrafficSyncWorker`/`TrafficApiClient`.
 */

/** A road a sample can be attributed to. */
data class RoadSegment(
    val id: String,
    val name: String?,
    val start: GeoPoint,
    val end: GeoPoint,
    val speedLimitKmh: Double?,
    val lengthMeters: Double = Geodesy.distanceMeters(start, end)
) {
    /** Heading of the segment, used to keep the two directions apart. */
    val bearingDegrees: Double get() = Geodesy.bearingDegrees(start, end)

    fun distanceTo(point: GeoPoint): Double = Geodesy.distanceToSegment(point, start, end)

    companion object {
        /**
         * Segments closer than this in the same direction are treated as the same road stretch for
         * aggregation, so one street does not fragment into hundreds of tiles.
         */
        const val SNAP_TOLERANCE_METERS = 25.0
        const val DIRECTION_TOLERANCE_DEGREES = 35.0
    }
}

/** One anonymous observation produced by a genuinely moving vehicle. */
data class SpeedObservation(
    val segmentId: String,
    val speedKmh: Double,
    val timestampMs: Long,
    val accuracyMeters: Float,
    val headingDegrees: Double,
    /** Rotating, resettable, non-reversible install token. Never a hardware id. */
    val reporterToken: String,
    val sampleCount: Int = 1
)

enum class CongestionLevel(val label: String) {
    FREE_FLOW("Free flow"),
    LIGHT("Light"),
    MODERATE("Moderate"),
    HEAVY("Heavy"),
    STANDSTILL("Standstill"),
    UNKNOWN("Unknown")
}

/** A report submitted by a person. Never generated by the app. */
data class TrafficIncident(
    val id: String,
    val kind: IncidentKind,
    val position: GeoPoint,
    val roadName: String?,
    val segmentId: String?,
    val reportedAtMs: Long,
    val expiresAtMs: Long,
    val reporterToken: String,
    val confirmations: Int = 0,
    val notes: String? = null
) {
    val active: Boolean get() = System.currentTimeMillis() < expiresAtMs
    val ageMinutes: Long get() = ((System.currentTimeMillis() - reportedAtMs) / 60_000L).coerceAtLeast(0L)
}

enum class IncidentKind(val label: String, val defaultLifetimeMinutes: Long) {
    ACCIDENT("Accident", 90),
    HAZARD("Road hazard", 180),
    CONSTRUCTION("Road works", 480),
    ROAD_CLOSED("Road closed", 720),
    POLICE("Police / checkpoint", 45),
    WEATHER("Weather hazard", 120),
    BROKEN_DOWN("Broken-down vehicle", 60)
}

/** Aggregated state of one segment. */
data class SegmentTrafficState(
    val segmentId: String,
    val segmentName: String?,
    val level: CongestionLevel,
    val averageSpeedKmh: Double?,
    val freeFlowSpeedKmh: Double?,
    val sampleCount: Int,
    val reporterCount: Int,
    val confidence: Double,
    val updatedAtMs: Long?,
    val ageMinutes: Long?,
    val incidents: List<TrafficIncident> = emptyList(),
    /** Set when the value came from a server aggregate rather than this device's own samples. */
    val source: TrafficSource = TrafficSource.DEVICE_SAMPLES
) {
    val isMeasured: Boolean get() = level != CongestionLevel.UNKNOWN
    val speedRatio: Double?
        get() = if (averageSpeedKmh != null && freeFlowSpeedKmh != null && freeFlowSpeedKmh > 0) {
            averageSpeedKmh / freeFlowSpeedKmh
        } else {
            null
        }
}

enum class TrafficSource(val label: String) {
    DEVICE_SAMPLES("This device"),
    COMMUNITY("Community observations"),
    HISTORY("Historical pattern"),
    UNKNOWN("No observations")
}

/** Result of aggregating a bucket of observations for one segment. */
data class TrafficAggregate(
    val level: CongestionLevel,
    val averageSpeedKmh: Double?,
    val sampleCount: Int,
    val reporterCount: Int,
    val confidence: Double,
    val newestTimestampMs: Long?,
    val freeFlowSpeedKmh: Double?
)

/**
 * Aggregation, confidence scoring and congestion classification.
 *
 * Confidence is a product of three independent factors, each in 0..1:
 *   volume    — how many independent samples exist (saturating, so one sample is never "certain"),
 *   recency   — exponentially decaying with the age of the newest sample,
 *   agreement — 1 minus the normalised spread of the samples (a stopped car next to a fast one is
 *               not a reliable "heavy traffic" claim).
 *
 * When confidence is below [minConfidenceForLevel] the result is UNKNOWN, which the UI renders grey.
 */
object TrafficAggregator {

    const val SAMPLE_WINDOW_MINUTES = 30L
    const val DEFAULT_FREE_FLOW_KMH = 50.0
    const val MIN_CONFIDENCE_FOR_LEVEL = 0.35
    const val RECENCY_HALF_LIFE_MINUTES = 12.0

    fun freeFlowSpeed(segment: RoadSegment, historical: List<Double> = emptyList()): Double {
        segment.speedLimitKmh?.takeIf { it in 10.0..160.0 }?.let { return it }
        // Without a posted limit, the 85th percentile of what really happened is a defensible
        // free-flow estimate; otherwise fall back to an explicit default and say so in the UI.
        if (historical.size >= 5) {
            val sorted = historical.sorted()
            val index = ((sorted.size - 1) * 0.85).toInt().coerceIn(0, sorted.size - 1)
            val value = sorted[index]
            if (value > 5.0) return value
        }
        return DEFAULT_FREE_FLOW_KMH
    }

    /** Classifies speed relative to free-flow. UNKNOWN when there is nothing measured. */
    fun classify(averageSpeedKmh: Double?, freeFlowKmh: Double?): CongestionLevel {
        if (averageSpeedKmh == null || freeFlowKmh == null || freeFlowKmh <= 0.0 || !averageSpeedKmh.isFinite()) {
            return CongestionLevel.UNKNOWN
        }
        val ratio = averageSpeedKmh / freeFlowKmh
        return when {
            ratio >= 0.85 -> CongestionLevel.FREE_FLOW
            ratio >= 0.65 -> CongestionLevel.LIGHT
            ratio >= 0.45 -> CongestionLevel.MODERATE
            ratio >= 0.2 -> CongestionLevel.HEAVY
            else -> CongestionLevel.STANDSTILL
        }
    }

    fun recencyFactor(ageMinutes: Double): Double {
        if (!ageMinutes.isFinite() || ageMinutes < 0) return 0.0
        return Math.pow(0.5, ageMinutes / RECENCY_HALF_LIFE_MINUTES)
    }

    /** 1 sample => ~0.35, 3 => ~0.61, 6 => ~0.76, 20 => ~0.92 (never 1.0). */
    fun volumeFactor(sampleCount: Int): Double {
        if (sampleCount <= 0) return 0.0
        return (ln(1.0 + sampleCount) / ln(1.0 + 30.0)).coerceIn(0.0, 1.0).let { 0.25 + 0.75 * it }
    }

    /** Uses the coefficient of variation, clamped so a single outlier cannot veto the bucket. */
    fun agreementFactor(speeds: List<Double>): Double {
        if (speeds.size <= 1) return 0.85
        val mean = speeds.average()
        if (mean <= 0.0) return 0.0
        val variance = speeds.sumOf { (it - mean) * (it - mean) } / (speeds.size - 1)
        val cv = kotlin.math.sqrt(variance) / mean
        return (1.0 - (cv / 1.2).coerceIn(0.0, 1.0)).coerceIn(0.15, 1.0)
    }

    fun confidence(sampleCount: Int, reporterCount: Int, ageMinutes: Double, speeds: List<Double>): Double {
        if (sampleCount <= 0) return 0.0
        val reporterBoost = when {
            reporterCount >= 5 -> 1.0
            reporterCount >= 2 -> 0.9
            else -> 0.75
        }
        val raw = volumeFactor(sampleCount) * recencyFactor(ageMinutes) * agreementFactor(speeds) * reporterBoost
        return raw.coerceIn(0.0, 0.99)
    }

    /**
     * Aggregates observations for a single segment. Observations outside the window are ignored
     * rather than aged into the average, so a segment stops being "green" once nobody drives it.
     */
    fun aggregate(
        segment: RoadSegment,
        observations: List<SpeedObservation>,
        nowMs: Long = System.currentTimeMillis(),
        historicalSpeeds: List<Double> = emptyList()
    ): TrafficAggregate {
        val windowStart = nowMs - SAMPLE_WINDOW_MINUTES * 60_000L
        val relevant = observations.filter {
            it.segmentId == segment.id &&
                it.timestampMs in windowStart..nowMs &&
                it.speedKmh.isFinite() &&
                it.speedKmh in 0.0..250.0
        }
        if (relevant.isEmpty()) {
            return TrafficAggregate(
                level = CongestionLevel.UNKNOWN,
                averageSpeedKmh = null,
                sampleCount = 0,
                reporterCount = 0,
                confidence = 0.0,
                newestTimestampMs = null,
                freeFlowSpeedKmh = freeFlowSpeed(segment, historicalSpeeds)
            )
        }
        // Weighted by sample count so a device that spent longer on the segment counts more, but
        // is capped so one device cannot dominate a bucket.
        val weighted = relevant.sumOf { it.speedKmh * it.sampleCount.coerceIn(1, 6) }
        val weightSum = relevant.sumOf { it.sampleCount.coerceIn(1, 6) }.toDouble()
        val average = weighted / weightSum
        val newest = relevant.maxOf { it.timestampMs }
        val ageMinutes = ((nowMs - newest) / 60_000.0).coerceAtLeast(0.0)
        val speeds = relevant.map { it.speedKmh }
        val confidence = confidence(
            sampleCount = relevant.sumOf { it.sampleCount.coerceIn(1, 6) },
            reporterCount = relevant.map { it.reporterToken }.distinct().size,
            ageMinutes = ageMinutes,
            speeds = speeds
        )
        val freeFlow = freeFlowSpeed(segment, historicalSpeeds)
        val level = if (confidence < MIN_CONFIDENCE_FOR_LEVEL) {
            CongestionLevel.UNKNOWN
        } else {
            classify(average, freeFlow)
        }
        return TrafficAggregate(
            level = level,
            averageSpeedKmh = average,
            sampleCount = relevant.sumOf { it.sampleCount.coerceIn(1, 6) },
            reporterCount = relevant.map { it.reporterToken }.distinct().size,
            confidence = confidence,
            newestTimestampMs = newest,
            freeFlowSpeedKmh = freeFlow
        )
    }
}

/**
 * Turns a stream of real GNSS fixes into speed observations.
 *
 * Samples are only produced when *all* of these hold: the device is genuinely moving, the fix is
 * accurate enough to attribute to a road, the fix passed the integrity monitor, the user opted in,
 * and the segment attribution is unambiguous. Otherwise nothing is recorded — silence is the
 * correct output, and the traffic layer stays UNKNOWN.
 */
class SpeedObservationRecorder(
    private val minSpeedKmh: Double = 4.0,
    private val maxAccuracyMeters: Float = 35f,
    private val minSegmentDurationMs: Long = 8_000L,
    private val maxSamplesPerSegment: Int = 6,
    private val reporterToken: String
) {
    private var currentSegmentId: String? = null
    private var segmentEnteredAtMs = 0L
    private var speedAccumulator = 0.0
    private var sampleCount = 0
    private var lastFixTimeMs = 0L
    private var lastPosition: GeoPoint? = null
    private var lastHeadingDegrees = 0.0
    private var lastAccuracyMeters = 0f
    private var lastSampleTimeMs = 0L

    data class RecorderState(
        val segmentId: String?,
        val secondsOnSegment: Long,
        val samples: Int
    )

    val state: RecorderState
        get() = RecorderState(
            segmentId = currentSegmentId,
            secondsOnSegment = if (currentSegmentId == null) 0 else ((System.currentTimeMillis() - segmentEnteredAtMs) / 1000L),
            samples = sampleCount
        )

    fun reset() {
        currentSegmentId = null
        segmentEnteredAtMs = 0L
        speedAccumulator = 0.0
        sampleCount = 0
        lastFixTimeMs = 0L
        lastPosition = null
        lastHeadingDegrees = 0.0
        lastAccuracyMeters = 0f
        lastSampleTimeMs = 0L
    }

    /**
     * Feeds one fix. Returns a completed [SpeedObservation] when the vehicle leaves a segment it
     * has been on long enough, otherwise null.
     */
    fun onFix(
        fix: GnssFix,
        segment: RoadSegment?,
        integrityCompromised: Boolean
    ): SpeedObservation? {
        if (integrityCompromised || segment == null) {
            val finished = finishCurrent()
            reset()
            lastFixTimeMs = fix.timeMs
            lastPosition = fix.position
            return finished
        }
        val speedKmh = fix.speedMps?.toDouble()?.times(3.6) ?: 0.0
        val usable = fix.accuracyMeters <= maxAccuracyMeters &&
            speedKmh >= minSpeedKmh &&
            segment.distanceTo(fix.position) <= RoadSegment.SNAP_TOLERANCE_METERS * 2 &&
            (lastFixTimeMs == 0L || fix.timeMs > lastFixTimeMs)

        if (!usable) {
            lastFixTimeMs = fix.timeMs
            return null
        }

        var finished: SpeedObservation? = null
        if (currentSegmentId != null && currentSegmentId != segment.id) {
            finished = finishCurrent()
        }
        if (currentSegmentId == null) {
            currentSegmentId = segment.id
            segmentEnteredAtMs = fix.timeMs
            speedAccumulator = 0.0
            sampleCount = 0
        }
        if (sampleCount < maxSamplesPerSegment) {
            speedAccumulator += speedKmh
            sampleCount++
        }
        fix.bearingDegrees?.takeIf { it.isFinite() }?.let { lastHeadingDegrees = it.toDouble() }
        lastAccuracyMeters = fix.accuracyMeters
        lastSampleTimeMs = fix.timeMs
        lastFixTimeMs = fix.timeMs
        lastPosition = fix.position
        return finished
    }

    /** Call when the trip/session ends so the last partial segment is not lost. */
    fun complete(nowMs: Long = System.currentTimeMillis()): SpeedObservation? {
        val observation = finishCurrent(nowMs)
        reset()
        return observation
    }

    private fun finishCurrent(nowMs: Long = System.currentTimeMillis()): SpeedObservation? {
        val segmentId = currentSegmentId ?: return null
        val durationMs = nowMs - segmentEnteredAtMs
        if (sampleCount == 0 || durationMs < minSegmentDurationMs) return null
        val average = speedAccumulator / sampleCount
        if (!average.isFinite() || average < minSpeedKmh) return null
        return SpeedObservation(
            segmentId = segmentId,
            speedKmh = average,
            timestampMs = if (lastSampleTimeMs > 0L) lastSampleTimeMs else nowMs,
            accuracyMeters = lastAccuracyMeters,
            headingDegrees = lastHeadingDegrees,
            reporterToken = reporterToken,
            sampleCount = sampleCount
        )
    }
}

/**
 * Maps a position to a road segment.
 *
 * Ambiguity is rejected on purpose: when two differently-named roads are within the snap tolerance
 * (a motorway running above a frontage road), no segment is returned and no sample is recorded.
 */
class SegmentMatcher(
    segments: List<RoadSegment>,
    private val toleranceMeters: Double = RoadSegment.SNAP_TOLERANCE_METERS
) {
    private val index: List<RoadSegment> = segments

    fun match(point: GeoPoint): RoadSegment? = matchDetailed(point).segment

    fun matchDetailed(point: GeoPoint): MatchResult {
        if (index.isEmpty()) return MatchResult(null, emptyList(), "No road segments loaded")
        val candidates = index
            .map { it to it.distanceTo(point) }
            .filter { it.second <= toleranceMeters }
            .sortedBy { it.second }
        if (candidates.isEmpty()) return MatchResult(null, emptyList(), "No road within ${toleranceMeters.toInt()} m")
        val best = candidates.first()
        val runnerUp = candidates.getOrNull(1)
        if (runnerUp != null && abs(runnerUp.second - best.second) < 3.0 && runnerUp.first.name != best.first.name) {
            return MatchResult(
                null,
                candidates.take(3).map { it.first },
                "Ambiguous: ${best.first.name ?: best.first.id} and ${runnerUp.first.name ?: runnerUp.first.id} overlap"
            )
        }
        return MatchResult(best.first, candidates.take(3).map { it.first }, null)
    }

    data class MatchResult(
        val segment: RoadSegment?,
        val candidates: List<RoadSegment>,
        val rejectionReason: String?
    )

    companion object {
        /** Decides whether a movement direction is along the segment or against it. */
        fun travelDirection(fix: GnssFix, segment: RoadSegment): Direction {
            val heading = fix.bearingDegrees?.toDouble() ?: return Direction.UNKNOWN
            val delta = Geodesy.bearingDifference(heading, segment.bearingDegrees)
            return when {
                delta <= RoadSegment.DIRECTION_TOLERANCE_DEGREES -> Direction.FORWARD
                delta >= 180.0 - RoadSegment.DIRECTION_TOLERANCE_DEGREES -> Direction.REVERSE
                else -> Direction.UNKNOWN
            }
        }
    }
}

enum class Direction { FORWARD, REVERSE, UNKNOWN }

/**
 * Stops the same incident being reported ten times in a minute, and stops an obviously bogus one
 * from reaching the community.
 */
class IncidentDeduplicator(
    private val duplicateRadiusMeters: Double = 120.0,
    private val duplicateWindowMs: Long = 15 * 60_000L,
    private val decayAfterConfirmations: Int = 3
) {
    private val recent = ArrayDeque<IncidentFingerprint>()

    data class IncidentFingerprint(
        val kind: IncidentKind,
        val position: GeoPoint,
        val timestampMs: Long,
        val reporterToken: String
    )

    data class Decision(
        val accepted: Boolean,
        val reason: String?,
        val mergeInto: String? = null,
        val confirmation: Boolean = false
    )

    fun evaluate(
        kind: IncidentKind,
        position: GeoPoint,
        reporterToken: String,
        existing: List<TrafficIncident>,
        nowMs: Long = System.currentTimeMillis()
    ): Decision {
        prune(nowMs)

        val ownRecent = recent.count { it.reporterToken == reporterToken && it.kind == kind }
        if (ownRecent >= 2) {
            return Decision(false, "You already reported this type of incident recently")
        }

        val match = existing.firstOrNull {
            it.kind == kind &&
                it.active &&
                Geodesy.distanceMeters(it.position, position) <= duplicateRadiusMeters
        }
        if (match != null) {
            if (match.reporterToken == reporterToken) {
                return Decision(false, "You already reported this incident", mergeInto = match.id)
            }
            return Decision(
                accepted = false,
                reason = "An identical report already exists nearby — counted as a confirmation",
                mergeInto = match.id,
                confirmation = true
            )
        }

        recent.addLast(IncidentFingerprint(kind, position, nowMs, reporterToken))
        return Decision(true, null)
    }

    fun record(incident: TrafficIncident) {
        recent.addLast(IncidentFingerprint(incident.kind, incident.position, incident.reportedAtMs, incident.reporterToken))
    }

    fun reset() {
        recent.clear()
    }

    private fun prune(nowMs: Long) {
        while (recent.isNotEmpty() && nowMs - recent.first().timestampMs > duplicateWindowMs) {
            recent.removeFirst()
        }
        while (recent.size > 64) recent.removeFirst()
    }
}

/**
 * Local rate limiter for anything that talks to the network (traffic upload, geocoding, routing).
 * Token bucket with a hard per-process ceiling; the server enforces its own limit as well.
 */
class TokenBucketRateLimiter(
    private val capacity: Int,
    private val refillPerMinute: Int,
    private val nowMs: () -> Long = System::currentTimeMillis
) {
    private var tokens = capacity.toDouble()
    private var lastRefillMs = nowMs()

    @Synchronized
    fun tryAcquire(count: Int = 1): Boolean {
        refill()
        if (tokens < count) return false
        tokens -= count
        return true
    }

    @Synchronized
    fun available(): Int {
        refill()
        return tokens.toInt()
    }

    private fun refill() {
        val now = nowMs()
        if (now <= lastRefillMs) return
        val elapsedMinutes = (now - lastRefillMs) / 60_000.0
        if (elapsedMinutes > 0) {
            tokens = (tokens + elapsedMinutes * refillPerMinute).coerceAtMost(capacity.toDouble())
            lastRefillMs = now
        }
    }
}

/** Converts traffic levels into the four colours the map legend promises. */
object TrafficColours {
    const val GREEN = "#22C55E"
    const val ORANGE = "#F59E0B"
    const val RED = "#EF4444"
    const val GREY = "#64748B"
    const val DEEP_RED = "#B91C1C"

    fun hexFor(level: CongestionLevel): String = when (level) {
        CongestionLevel.FREE_FLOW -> GREEN
        CongestionLevel.LIGHT -> GREEN
        CongestionLevel.MODERATE -> ORANGE
        CongestionLevel.HEAVY -> RED
        CongestionLevel.STANDSTILL -> DEEP_RED
        CongestionLevel.UNKNOWN -> GREY
    }

    fun legend(): List<Pair<CongestionLevel, String>> = listOf(
        CongestionLevel.FREE_FLOW to GREEN,
        CongestionLevel.MODERATE to ORANGE,
        CongestionLevel.HEAVY to RED,
        CongestionLevel.UNKNOWN to GREY
    )
}

/** Validates a report before it is stored or uploaded. */
object IncidentValidator {

    data class Validation(val accepted: Boolean, val reason: String?)

    fun validate(
        kind: IncidentKind,
        position: GeoPoint,
        nowMs: Long = System.currentTimeMillis(),
        lastFixAgeMs: Long?,
        accuracyMeters: Float?,
        integrityCompromised: Boolean,
        notes: String?
    ): Validation {
        if (integrityCompromised) {
            return Validation(false, "Location integrity check failed — reporting is disabled")
        }
        if (accuracyMeters == null || accuracyMeters > 200f) {
            return Validation(false, "Fix accuracy is too poor to place a report (${accuracyMeters?.toInt() ?: "unknown"} m)")
        }
        if (lastFixAgeMs == null || lastFixAgeMs > 60_000) {
            return Validation(false, "The last fix is older than one minute")
        }
        if (!position.isValid) return Validation(false, "Coordinates are out of range")
        if (kind.defaultLifetimeMinutes <= 0) return Validation(false, "Unknown incident type")
        if (notes != null && notes.length > 280) return Validation(false, "Notes are limited to 280 characters")
        if (notes != null && notes.any { it.code < 0x20 && it != '\n' }) {
            return Validation(false, "Notes contain control characters")
        }
        return Validation(true, null)
    }
}

/** Formats the age of a report the way the traffic list shows it. */
fun formatAge(minutes: Long?): String = when {
    minutes == null -> "no data"
    minutes <= 0 -> "just now"
    minutes == 1L -> "1 min ago"
    minutes < 60 -> "$minutes min ago"
    else -> "${minutes / 60} h ago"
}

/** Percentage label with no false precision. */
fun formatConfidence(value: Double): String = "${(value * 100).roundToInt()}%"
