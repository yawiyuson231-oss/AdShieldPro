package com.adshield.pro.ui.screens.intelligence

import androidx.compose.foundation.layout.Box
import androidx.compose.foundation.layout.fillMaxSize
import androidx.compose.runtime.Composable
import androidx.compose.runtime.LaunchedEffect
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableIntStateOf
import androidx.compose.runtime.mutableLongStateOf
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue
import androidx.compose.runtime.toMutableStateList
import androidx.compose.runtime.withFrameNanos
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import com.adshield.pro.domain.intelligence.IntelligenceAction
import com.adshield.pro.domain.intelligence.IntelligenceEvent
import com.adshield.pro.domain.intelligence.IntelligenceModule
import com.adshield.pro.domain.intelligence.IntelligenceSeverity
import com.adshield.pro.domain.intelligence.IntelligenceTimeRange
import com.adshield.pro.domain.intelligence.NodePosition
import com.adshield.pro.ui.model.IntelligenceMapUiState
import com.adshield.pro.ui.model.MapCameraTarget

/**
 * OMNISHIELD X — Live Intelligence Map screen.
 *
 * Layout: a full-bleed interactive canvas, a collapsible command panel docked above the bottom
 * navigation, and bottom sheets for node detail and the event timeline. All state comes in from
 * [IntelligenceMapUiState]; the only local state is presentation (camera, pulses, which sheet is
 * open), which keeps the map independent from the module screens.
 */
@Composable
fun IntelligenceMapScreen(
    uiState: IntelligenceMapUiState,
    onToggleLive: () -> Unit,
    onSelectModule: (IntelligenceModule?) -> Unit,
    onSelectEvent: (IntelligenceEvent) -> Unit,
    onCenterOnModule: (IntelligenceModule) -> Unit,
    onResetCamera: () -> Unit,
    onSetEditingLayout: (Boolean) -> Unit,
    onResetLayout: () -> Unit,
    onMoveNode: (IntelligenceModule, NodePosition) -> Unit,
    onSetModuleFilter: (IntelligenceModule?) -> Unit,
    onSetSeverityFilter: (IntelligenceSeverity?) -> Unit,
    onSetTimeRange: (IntelligenceTimeRange) -> Unit,
    onSetQuery: (String) -> Unit,
    onClearFilters: () -> Unit,
    onClearHistory: () -> Unit,
    onAction: (IntelligenceAction, IntelligenceModule) -> Unit,
    onOpenModule: (IntelligenceModule) -> Unit,
    modifier: Modifier = Modifier
) {
    val cameraState = remember { IntelligenceCameraState() }
    var commandExpanded by remember { mutableStateOf(true) }
    var timelineOpen by remember { mutableStateOf(false) }
    var inspectedModule by remember { mutableStateOf<IntelligenceModule?>(null) }
    var quickActionsModule by remember { mutableStateOf<IntelligenceModule?>(null) }
    var pendingAction by remember { mutableStateOf<Pair<IntelligenceAction, IntelligenceModule>?>(null) }
    var confirmClearHistory by remember { mutableStateOf(false) }

    val pulses = remember { mutableListOf<MapPulse>().toMutableStateList() }
    var frameNanos by remember { mutableLongStateOf(0L) }
    var pulseTick by remember { mutableIntStateOf(0) }
    val primed = remember { mutableStateOf(false) }
    val knownEventIds = remember { mutableSetOf<Long>() }
    val openedAtMs = remember { System.currentTimeMillis() }

    // Camera commands generated by the ViewModel (reset, focus module, locate event).
    LaunchedEffect(uiState.cameraCommand?.token) {
        val command = uiState.cameraCommand ?: return@LaunchedEffect
        while (cameraState.viewport.width <= 0f) {
            withFrameNanos { }
        }
        when (val target = command.target) {
            MapCameraTarget.FitAll -> cameraState.animateReset()
            is MapCameraTarget.OnModule -> {
                val position = uiState.nodePositions[target.module]
                if (position != null) {
                    cameraState.animateFocusOnWorld(MapGeometry.worldPosition(position))
                }
            }
            is MapCameraTarget.OnEvent -> {
                val position = uiState.nodePositions[target.module]
                if (position != null) {
                    cameraState.animateFocusOnWorld(
                        MapGeometry.eventMarkerWorld(position, slotIndex = 0, slotCount = 1)
                    )
                }
            }
        }
    }

    // Create pulses only for genuinely new, recent events; prime on the first emission so the
    // stored history does not replay as if it were happening now.
    LaunchedEffect(uiState.allEvents, uiState.isLive) {
        if (!uiState.isLive) return@LaunchedEffect
        if (!primed.value) {
            knownEventIds.addAll(uiState.allEvents.map { it.id })
            primed.value = true
            return@LaunchedEffect
        }
        val newOnes = uiState.allEvents.filter { it.id !in knownEventIds }
        if (newOnes.isEmpty()) return@LaunchedEffect
        knownEventIds.addAll(newOnes.map { it.id })
        val recent = newOnes.filter { it.timestampEpochMs >= openedAtMs - RECENT_EVENT_WINDOW_MS }
        if (recent.isEmpty()) return@LaunchedEffect
        val now = System.nanoTime()
        recent.sortedBy { it.timestampEpochMs }.take(MAX_LIVE_PULSES).forEach { event ->
            pulses += MapPulse(event.id, event.module, event.severity, now)
        }
        while (pulses.size > MAX_TRACKED_PULSES) pulses.removeAt(0)
        pulseTick++
    }

    // Frame loop exists only while a pulse is in flight. No pulses → no animation work at all.
    LaunchedEffect(pulseTick, uiState.isLive) {
        if (!uiState.isLive || pulses.isEmpty()) return@LaunchedEffect
        while (true) {
            var active = false
            withFrameNanos { now ->
                frameNanos = now
                pulses.removeAll { now - it.startNanos > MapGeometry.PULSE_DURATION_NANOS }
                active = pulses.isNotEmpty()
            }
            if (!active) break
        }
    }

    LaunchedEffect(uiState.isLive) {
        if (!uiState.isLive) {
            pulses.clear()
            frameNanos = 0L
        }
    }

    Box(modifier = modifier.fillMaxSize()) {
        IntelligenceMapCanvas(
            uiState = uiState,
            cameraState = cameraState,
            pulses = pulses,
            frameNanos = frameNanos,
            modifier = Modifier.fillMaxSize(),
            onTapModule = { module ->
                onSelectModule(module)
                inspectedModule = module
            },
            onLongPressModule = { module ->
                onSelectModule(module)
                quickActionsModule = module
            },
            onTapEventMarker = { event ->
                onSelectEvent(event)
                inspectedModule = event.module
            },
            onTapEmpty = {
                onSelectModule(null)
                inspectedModule = null
            },
            onMoveNode = onMoveNode
        )

        IntelligenceTopBar(
            state = uiState,
            onToggleLive = onToggleLive,
            onOpenTimeline = { timelineOpen = true },
            onResetCamera = onResetCamera,
            onToggleLayoutEditing = { onSetEditingLayout(!uiState.isEditingLayout) },
            onResetLayout = onResetLayout,
            onOpenCommandPanel = { commandExpanded = !commandExpanded },
            modifier = Modifier.align(Alignment.TopCenter)
        )

        IntelligenceCommandPanel(
            state = uiState,
            expanded = commandExpanded,
            onToggleExpanded = { commandExpanded = !commandExpanded },
            onSelectModule = { module ->
                onSelectModule(module)
                inspectedModule = module
            },
            onOpenModule = onOpenModule,
            onOpenTimeline = { timelineOpen = true },
            modifier = Modifier.align(Alignment.BottomCenter)
        )
    }

    inspectedModule?.let { module ->
        NodeDetailSheet(
            state = uiState,
            module = module,
            onDismiss = { inspectedModule = null },
            onOpenModule = { target ->
                inspectedModule = null
                onOpenModule(target)
            },
            onRequestAction = { action, owner ->
                if (action.requiresConfirmation) {
                    pendingAction = action to owner
                } else {
                    onAction(action, owner)
                }
            },
            onSelectEvent = { event ->
                inspectedModule = null
                timelineOpen = false
                onSelectEvent(event)
            },
            onCenterOnModule = { onCenterOnModule(it) }
        )
    }

    if (timelineOpen) {
        IntelligenceTimelineSheet(
            state = uiState,
            onDismiss = { timelineOpen = false },
            onSetModule = onSetModuleFilter,
            onSetSeverity = onSetSeverityFilter,
            onSetRange = onSetTimeRange,
            onSetQuery = onSetQuery,
            onClearFilters = onClearFilters,
            onSelectEvent = { event ->
                timelineOpen = false
                inspectedModule = null
                onSelectEvent(event)
            },
            onRequestClearHistory = { confirmClearHistory = true }
        )
    }

    quickActionsModule?.let { module ->
        ModuleQuickActionsDialog(
            module = module,
            state = uiState,
            onDismiss = { quickActionsModule = null },
            onInspect = {
                quickActionsModule = null
                inspectedModule = module
            },
            onCenter = {
                quickActionsModule = null
                onCenterOnModule(module)
            },
            onOpenModule = {
                quickActionsModule = null
                onOpenModule(module)
            },
            onRequestAction = { action ->
                quickActionsModule = null
                if (action.requiresConfirmation) {
                    pendingAction = action to module
                } else {
                    onAction(action, module)
                }
            }
        )
    }

    pendingAction?.let { (action, module) ->
        ActionConfirmationDialog(
            action = action,
            module = module,
            onConfirm = {
                pendingAction = null
                onAction(action, module)
            },
            onDismiss = { pendingAction = null }
        )
    }

    if (confirmClearHistory) {
        ClearHistoryConfirmationDialog(
            onConfirm = {
                confirmClearHistory = false
                timelineOpen = false
                onClearHistory()
            },
            onDismiss = { confirmClearHistory = false }
        )
    }
}

private const val MAX_LIVE_PULSES = 6
private const val MAX_TRACKED_PULSES = 12
private const val RECENT_EVENT_WINDOW_MS = 45_000L
